// 根据当前视频 Episode 获取 AI 标注候选 (演示预置)
export function getCandidatesForEpisode(episode) {
  let list = [];
  if (!episode) list = MOCK_CANDIDATES;
  else if (
    episode.episodeId === 'EP-2096837217907154945' ||
    episode.fileName?.includes('DM_20260814') ||
    episode.name?.includes('螺丝') ||
    episode.name?.includes('新动力') ||
    episode.name?.includes('打螺丝')
  ) {
    const total = episode.totalFrames || 9177;
    list = MOCK_CANDIDATES_SCREW_ASSEMBLY.map(c => ({
      ...c,
      endFrame: c.candidateId === 'cand-screw-12' ? total : Math.min(total, c.endFrame),
    }));
  } else if (episode.episodeId === 'EP-SESSION-028-L') {
    list = MOCK_CANDIDATES_LEFT_HAND;
  } else if (episode.episodeId === 'EP-SESSION-028') {
    list = MOCK_CANDIDATES;
  } else if (episode.initialSteps && episode.initialSteps.length > 0) {
    list = episode.initialSteps.map((s, idx) => ({
      candidateId: `cand-demo-${idx + 1}`,
      stepNo: s.stepNo || idx + 1,
      arm: s.arm,
      effector: s.effector,
      skill: s.skill,
      actionSkill: s.actionSkill || s.skill,
      object: s.object,
      actionTarget: s.actionTarget || s.object,
      goal: s.goal,
      expectedGoal: s.expectedGoal || s.goal,
      startFrame: s.startFrame,
      endFrame: s.endFrame,
      stepContent: s.stepContent,
      description: s.notes || s.stepContent,
    }));
  } else {
    // 本地自定义上传视频初始无候选，等待大模型真实推理生成，杜绝预设假候选
    return [];
  }

  return list.map(item => ({
    ...item,
    isDemo: true,
    source: 'demo_template',
    confidence: null,
    displayConfidence: '演示预置 (Demo)',
    needsReview: true,
  }));
}

